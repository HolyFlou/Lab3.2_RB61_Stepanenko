#ifndef FUNCS_H
#define FUNCS_H

/**
 * @brief Обчислює значення нелінійної функції f(x) = x^3 - x - 4.
 *
 * @details Використовується як основне рівняння f(x) = 0 для пошуку кореня 
 * на заданому інтервалі [a, b].
 *
 * @param x Точка, у якій обчислюється значення функції.
 *
 * @return Значення функції f(x) у точці x.
 */
double f(double x);

/**
 * @brief Обчислює значення першої похідної f'(x) = 3x^2 - 1.
 *
 * @details Використовується для аналітичної перевірки монотонності функції 
 * та підтвердження наявності єдиного кореня на проміжку.
 *
 * @param x Точка, у якій обчислюється перша похідна.
 *
 * @return Значення першої похідної f'(x) у точці x.
 */
double f_prime(double x);

/**
 * @brief Обчислює значення другої похідної f''(x) = 6x.
 *
 * @details Використовується для аналізу опуклості графіка функції та вибору 
 * нерухомої точки у методі хорд за умовою f(x) * f''(x) > 0.
 *
 * @param x Точка, у якій обчислюється друга похідна.
 *
 * @return Значення другої похідної f''(x) у точці x.
 */
double f_double_prime(double x);

/**
 * @brief Обробляє ситуацію перевищення максимальної кількості ітерацій.
 *
 * @details Інтерактивно запитує у користувача подальшу дію, якщо алгоритм 
 * не досяг заданої точності eps за відведену кількість кроків.
 *
 * @param current_iter Поточна кількість виконаних ітерацій.
 * @param current_x    Поточне знайдене наближення кореня.
 *
 * @return Код обраної дії: 1 — продовжити на max_iter ітерацій, 
 *         2 — виконувати до досягнення точності без обмежень, 0 — перервати обчислення.
 */
int handle_max_iter_exceeded(int current_iter, double current_x);

/**
 * @brief Знаходить корінь нелінійного рівняння методом половинного ділення (дихотомії).
 *
 * @details Послідовно ділить навпіл відрізок [a, b] та вибирає ту половину, 
 * на кінцях якої функція змінює знак. Підтримує режим налагодження та замір часу.
 *
 * @param a         Ліва межа початкового інтервалу.
 * @param b         Права межа початкового інтервалу.
 * @param eps       Задана точність обчислення кореня (критерій зупинки).
 * @param max_iter  Максимально допустима кількість ітерацій до запиту користувача.
 * @param debug     Прапорець режиму налагодження (1 — покроковий вивід, 0 — вимкнено).
 *
 * @return Функція не повертає значення, а виводить результати обчислень у консоль.
 */
void solve_bisection(double a, double b, double eps, int max_iter, int debug);

/**
 * @brief Знаходить корінь нелінійного рівняння методом хорд.
 *
 * @details Визначає нерухому точку за допомогою другої похідної та проводить хорди 
 * від рухомого наближення до нерухомої точки. Підтримує замір часу та режим налагодження.
 *
 * @param a         Ліва межа початкового інтервалу.
 * @param b         Права межа початкового інтервалу.
 * @param eps       Задана точність обчислення кореня (критерій зупинки).
 * @param max_iter  Максимально допустима кількість ітерацій до запиту користувача.
 * @param debug     Прапорець режиму налагодження (1 — покроковий вивід, 0 — вимкнено).
 *
 * @return Функція не повертає значення, а виводить результати обчислень у консоль.
 */
void solve_chord(double a, double b, double eps, int max_iter, int debug);

#endif // FUNCS_H